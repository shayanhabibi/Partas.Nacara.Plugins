namespace Nacara.Plugins

open System
open System.Globalization
open System.IO
open System.Reflection
open System.Text.Encodings.Web
open System.Text.Json

/// <summary>Hovers compiled to a script that plays them with anime.js.</summary>
module MotionScript =

    let private encoding =
        JsonSerializerOptions(Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping)

    let private literal (text: string) = JsonSerializer.Serialize(text, encoding)

    let private number (x: float) =
        (Math.Round(x, 3, MidpointRounding.AwayFromZero) + 0.0).ToString("0.###", CultureInfo.InvariantCulture)

    let private springOf (parameters: SpringParameters) =
        let anime = Spring.forAnime parameters

        "spring({ mass: "
        + number anime.Mass
        + ", stiffness: "
        + number anime.Stiffness
        + ", damping: "
        + number anime.Damping
        + " })"

    let private ease (easing: Easing) =
        match easing with
        | Linear -> "\"linear\""
        | CubicBezier(x1, y1, x2, y2) -> $"cubicBezier(%s{number x1}, %s{number y1}, %s{number x2}, %s{number y2})"
        | Easing.Spring parameters -> springOf parameters
        | SpringPreset name ->
            match Spring.preset name with
            | Some parameters -> springOf parameters
            | None -> "\"linear\""

    // A token is read when the hover starts, from the element it hovers: the colour scheme may
    // have changed since the page loaded, and anime.js cannot interpolate var().
    let private resolver (value: MotionValue) =
        match value with
        | Literal css -> "() => " + literal css
        | Token _ ->
            let name = (MotionCss.value value).Substring("var(".Length).TrimEnd(')')
            "(host) => getComputedStyle(host).getPropertyValue(" + literal name + ")"

    let private change (change: Change) =
        "{ property: " + literal change.Property + ", to: " + resolver change.To + " }"

    let private groups (hover: Hover) =
        hover.Changes
        |> List.groupBy (fun c -> c.Part)
        |> List.map (fun (part, changes) ->
            let part =
                match part with
                | Some selector -> literal selector
                | None -> "null"

            let lines =
                changes |> List.map (fun c -> "        " + change c + ",") |> String.concat "\n"

            "      { part: " + part + ", changes: [\n" + lines + "\n      ] },")
        |> String.concat "\n"

    let private config (hover: Hover) =
        String.concat
            "\n"
            [
                "  {"
                "    selector: " + literal hover.Selector + ","
                "    duration: " + string (MotionCss.duration hover) + ","
                "    ease: " + ease hover.Easing + ","
                "    groups: ["
                groups hover
                "    ],"
                "  },"
            ]

    let private usesSpring (hovers: Hover list) =
        hovers
        |> List.exists (fun h ->
            match h.Easing with
            | Easing.Spring _ -> true
            | SpringPreset name -> (Spring.preset name).IsSome
            | _ -> false)

    let private usesBezier (hovers: Hover list) =
        hovers
        |> List.exists (fun h ->
            match h.Easing with
            | CubicBezier _ -> true
            | _ -> false)

    let private names (hovers: Hover list) =
        [
            "createAnimatable"
            if usesSpring hovers then
                "spring"
            if usesBezier hovers then
                "cubicBezier"
        ]

    let private reducedQuery = "(prefers-reduced-motion: reduce)"

    let private template =
        """// Generated by Partas.Nacara.Plugins.Motion from the Figma motion document.
const hovers = [
@HOVERS@
];

const camel = (property) => property.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

// A number, or the list of numbers, anime.js tweens for a css value: the browser resolves the
// value on a probe so a colour arrives as its channels and a length as its pixels.
const probe = document.createElement("span");
probe.hidden = true;
const numbers = (property, raw) => {
  probe.style.setProperty(property, raw);
  const computed = getComputedStyle(probe).getPropertyValue(property);
  probe.style.removeProperty(property);
  const found = computed.match(/-?\d*\.?\d+(?:e[-+]?\d+)?/gi);
  if (!found) return null;
  const values = found.map(Number);
  return values.length === 1 ? values[0] : values;
};

const bind = (host, hover) => {
  const duration = () => @DURATION@;
  const targets = [];
  for (const group of hover.groups) {
    const elements = group.part ? host.querySelectorAll(group.part) : [host];
    for (const element of elements) {
      const settings = {};
      for (const change of group.changes)
        settings[camel(change.property)] = { duration: duration(), ease: hover.ease };
      targets.push({ animatable: createAnimatable(element, settings), changes: group.changes });
    }
  }

  const held = new Set();
  let rest = [];
  const enter = (source) => {
    held.add(source);
    if (held.size > 1) return;
    // Where each property is now, so leaving returns to it however the hover was interrupted.
    rest = targets.map(({ animatable, changes }) =>
      changes.map((change) => {
        const current = animatable[camel(change.property)]();
        return Array.isArray(current) ? [...current] : current;
      }));
    for (const { animatable, changes } of targets)
      for (const change of changes) {
        const to = numbers(change.property, change.to(host));
        if (to !== null) animatable[camel(change.property)](to, duration());
      }
  };
  const leave = (source) => {
    held.delete(source);
    if (held.size > 0) return;
    targets.forEach(({ animatable, changes }, index) =>
      changes.forEach((change, at) => animatable[camel(change.property)](rest[index][at], duration())));
  };

  host.addEventListener("mouseenter", () => enter("pointer"));
  host.addEventListener("mouseleave", () => leave("pointer"));
  host.addEventListener("focus", () => enter("focus"));
  host.addEventListener("blur", () => leave("focus"));
};

const attach = () => {
@GUARD@  document.body.appendChild(probe);
  for (const hover of hovers)
    for (const host of document.querySelectorAll(hover.selector)) bind(host, hover);
};

if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", attach);
else attach();
"""

    let private body (policy: ReducedMotion) (hovers: Hover list) =
        let duration =
            match policy with
            | Instant -> "matchMedia(\"" + reducedQuery + "\").matches ? 0 : hover.duration"
            | _ -> "hover.duration"

        let guard =
            match policy with
            | Off -> "  if (matchMedia(\"" + reducedQuery + "\").matches) return;\n"
            | _ -> ""

        template
            .Replace("@HOVERS@", hovers |> List.map config |> String.concat "\n")
            .Replace("@DURATION@", duration)
            .Replace("@GUARD@", guard)

    let private indent (text: string) =
        text.TrimEnd('\n').Split '\n'
        |> Array.map (fun line -> if line = "" then line else "  " + line)
        |> String.concat "\n"

    /// <summary>The script that plays the hovers.</summary>
    /// <remarks>
    /// <para>A bundled source starts with a static import of <c>./anime.esm.js</c> that names only what the hovers use, for the site's bundler to resolve. A CDN source holds no static import: it loads the module with <c>import()</c> inside an async function, so it runs as a classic script.</para>
    /// <para>A token value is read with <c>getComputedStyle</c> each time a hover starts, never written as <c>var()</c>.</para>
    /// </remarks>
    /// <param name="source">Where anime.js comes from.</param>
    /// <param name="policy">What the script does for visitors who ask for reduced motion.</param>
    /// <param name="hovers">The hovers to play.</param>
    let entry (source: AnimeSource) (policy: ReducedMotion) (hovers: Hover list) : string =
        let names = names hovers |> String.concat ", "
        let body = body policy hovers

        match source with
        | Bundled -> "import { " + names + " } from \"./anime.esm.js\";\n\n" + body
        | Cdn url ->
            "(async () => {\n  const url = "
            + literal url
            + ";\n  const anime = await import(url);\n  const { "
            + names
            + " } = anime;\n\n"
            + indent body
            + "\n})();\n"

    /// <summary>The anime.js 4.5.0 module embedded in the package.</summary>
    let anime () : string =
        use stream = Assembly.GetExecutingAssembly().GetManifestResourceStream "anime.esm.js"
        use reader = new StreamReader(stream)
        reader.ReadToEnd()
