namespace Nacara.Plugins

open System
open System.Globalization
open System.IO
open System.Reflection
open System.Text.Encodings.Web
open System.Text.Json

/// <summary>Hovers compiled to a script that plays them with anime.js.</summary>
module MotionScript =

    let private encoding =
        JsonSerializerOptions(Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping)

    let private literal (text: string) = JsonSerializer.Serialize(text, encoding)

    let private number (x: float) =
        (Math.Round(x, 3, MidpointRounding.AwayFromZero) + 0.0).ToString("0.###", CultureInfo.InvariantCulture)

    let private springOf (parameters: SpringParameters) =
        let anime = Spring.forAnime parameters

        "spring({ mass: "
        + number anime.Mass
        + ", stiffness: "
        + number anime.Stiffness
        + ", damping: "
        + number anime.Damping
        + " })"

    // A preset plays the samples of CSS's linear() over 1200ms, not anime.js's spring: both engines
    // then play the same curve for the same time, as Figma plays a preset over 1200ms.
    let private sampledOf (parameters: SpringParameters) =
        let linear = Spring.linear parameters
        "sampled([" + linear.Substring("linear(".Length).TrimEnd(')') + "])"

    let private ease (easing: Easing) =
        match easing with
        | Linear -> "\"linear\""
        | CubicBezier(x1, y1, x2, y2) -> $"cubicBezier(%s{number x1}, %s{number y1}, %s{number x2}, %s{number y2})"
        | Easing.Spring parameters -> springOf parameters
        | SpringPreset name ->
            match Spring.preset name with
            | Some parameters -> sampledOf parameters
            | None -> "\"linear\""

    // A token is read when the hover starts, from the element it hovers: the colour scheme may
    // have changed since the page loaded, and anime.js cannot interpolate var().
    let private resolver (value: MotionValue) =
        match value with
        | Literal css -> "() => " + literal css
        | Token(path, fallback) ->
            let read =
                "getComputedStyle(host).getPropertyValue(" + literal (MotionCss.customProperty path) + ").trim()"

            match fallback with
            | Some css -> "(host) => " + read + " || " + literal css
            | None -> "(host) => " + read

    let private change (change: Change) =
        "{ property: " + literal change.Property + ", to: " + resolver change.To + " }"

    let private groups (hover: Hover) =
        hover.Changes
        |> List.groupBy (fun c -> c.Part)
        |> List.map (fun (part, changes) ->
            let part =
                match part with
                | Some selector -> literal selector
                | None -> "null"

            let lines =
                changes |> List.map (fun c -> "        " + change c + ",") |> String.concat "\n"

            "      { part: " + part + ", changes: [\n" + lines + "\n      ] },")
        |> String.concat "\n"

    let private config (hover: Hover) =
        String.concat
            "\n"
            [
                "  {"
                "    selector: " + literal hover.Selector + ","
                "    duration: " + string (MotionCss.duration hover) + ","
                "    ease: " + ease hover.Easing + ","
                "    groups: ["
                groups hover
                "    ],"
                "  },"
            ]

    let private usesSpring (hovers: Hover list) =
        hovers
        |> List.exists (fun h ->
            match h.Easing with
            | Easing.Spring _ -> true
            | _ -> false)

    let private usesBezier (hovers: Hover list) =
        hovers
        |> List.exists (fun h ->
            match h.Easing with
            | CubicBezier _ -> true
            | _ -> false)

    let private names (hovers: Hover list) =
        [
            "animate"
            if usesSpring hovers then
                "spring"
            if usesBezier hovers then
                "cubicBezier"
        ]

    let private reducedQuery = "(prefers-reduced-motion: reduce)"

    let private template =
        """// Generated by Partas.Nacara.Plugins.Motion from the Figma motion document.

// A Figma preset's ease: the samples of its CSS linear(), joined by straight lines, as CSS plays it.
const sampled = (points) => (t) => {
  const at = Math.min(Math.max(t, 0), 1) * (points.length - 1);
  const i = Math.min(Math.floor(at), points.length - 2);
  return points[i] + (points[i + 1] - points[i]) * (at - i);
};

const hovers = [
@HOVERS@
];

const camel = (property) => property.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

// anime.js takes rotate for a part of transform, which would turn the element on top of the CSS
// rotate property and stay in transform. The CSS property is tweened instead, through a custom
// property it reads while the hover plays.
const through = { rotate: "--nacara-motion-rotate" };
const key = (property) => through[property] || camel(property);

// anime.js cannot parse color(srgb ...), which is how a browser writes color-mix(), so every
// colour is rewritten as rgba() by painting it on a canvas pixel.
const canvas = document.createElement("canvas");
canvas.width = canvas.height = 1;
const context = canvas.getContext("2d", { willReadFrequently: true });
const colour = /(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\([^)]*\)/g;
const rgba = (text) =>
  text.replace(colour, (match) => {
    context.clearRect(0, 0, 1, 1);
    context.fillStyle = "#000";
    context.fillStyle = match;
    context.fillRect(0, 0, 1, 1);
    const [r, g, b, a] = context.getImageData(0, 0, 1, 1).data;
    return `rgba(${r}, ${g}, ${b}, ${Math.round((a / 255) * 1000) / 1000})`;
  });

// What the browser makes of a css value under the hovered element, so var() resolves in its scope.
// A border-radius is read as its four corners, so rest and target have the same shape: a computed
// shorthand collapses (8px, 4px 8px) and anime.js would pad the shorter one with zeros.
const corners = ["top-left", "top-right", "bottom-right", "bottom-left"];
const current = (element, property) =>
  property === "border-radius"
    ? corners.map((corner) => getComputedStyle(element).getPropertyValue(`border-${corner}-radius`)).join(" ")
    : getComputedStyle(element).getPropertyValue(property);

const probe = document.createElement("span");
probe.hidden = true;
const resolve = (host, property, raw) => {
  host.appendChild(probe);
  probe.style.setProperty(property, raw);
  const computed = current(probe, property);
  probe.style.removeProperty(property);
  probe.remove();
  return computed.trim() ? rgba(computed) : null;
};

// The same value with nothing in it, for a property that rests at none: a transparent shadow of
// the shape the hover ends on, 0px 0px for a translate, 0deg for a rotate. Every length and angle
// is zeroed, whatever its unit.
const zeroOf = (value) =>
  value.replace(/rgba\([^)]*\)/g, "rgba(0, 0, 0, 0)").replace(/(?<![#\w.])-?(?:\d+\.?\d*|\.\d+)([a-z%]+)/gi, "0$1");

const bind = (host, hover) => {
  const duration = () => @DURATION@;
  const targets = [];
  for (const group of hover.groups)
    for (const element of group.part ? host.querySelectorAll(group.part) : [host])
      targets.push({ element, changes: group.changes });

  const held = new Set();
  let rest = null;
  let generation = 0;

  // One animation per element, replacing whatever is running so it starts from what is rendered.
  const play = (values, done) => {
    const stamp = ++generation;
    const moving = targets.filter((_, index) => Object.keys(values[index]).length > 0);
    let pending = moving.length;
    if (pending === 0 && done) done();
    targets.forEach(({ element }, index) => {
      if (Object.keys(values[index]).length === 0) return;
      // A physical ease plays for its own settling time and ignores the duration, so instant means a plain one.
      const params = { duration: duration(), ease: duration() === 0 ? "linear" : hover.ease, composition: "replace" };
      for (const property in values[index]) params[key(property)] = values[index][property];
      params.onComplete = () => {
        if (stamp === generation && --pending === 0 && done) done();
      };
      animate(element, params);
    });
  };

  const enter = (source) => {
    held.add(source);
    if (held.size > 1) return;
    const to = targets.map(({ changes }) => {
      const values = {};
      for (const change of changes) {
        const value = resolve(host, change.property, change.to(host));
        if (value !== null) values[change.property] = value;
      }
      return values;
    });
    // Rest is read only while idle: an interrupted hover must not take its own tween for the rest.
    if (rest === null)
      rest = targets.map(({ element }, index) => {
        const values = {};
        for (const property in to[index]) {
          const now = rgba(current(element, property));
          values[property] = now === "none" ? zeroOf(to[index][property]) : now;
          if (through[property]) {
            element.style.setProperty(through[property], values[property]);
            element.style.setProperty(property, `var(${through[property]})`);
          } else if (now === "none") element.style.setProperty(property, values[property]);
        }
        return values;
      });
    play(to);
  };

  const leave = (source) => {
    if (!held.delete(source) || held.size > 0 || rest === null) return;
    play(rest, () => {
      // Back at rest: hand the properties back to the stylesheet.
      for (const { element, changes } of targets)
        for (const change of changes) {
          element.style.removeProperty(change.property);
          if (through[change.property]) element.style.removeProperty(through[change.property]);
        }
      rest = null;
    });
  };

  host.addEventListener("mouseenter", () => enter("pointer"));
  host.addEventListener("mouseleave", () => leave("pointer"));
  host.addEventListener("focus", () => {
    if (host.matches(":focus-visible")) enter("focus");
  });
  host.addEventListener("blur", () => leave("focus"));
};

const attach = () => {
@GUARD@  for (const hover of hovers)
    for (const host of document.querySelectorAll(hover.selector)) bind(host, hover);
};

if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", attach);
else attach();
"""

    let private body (policy: ReducedMotion) (hovers: Hover list) =
        let duration =
            match policy with
            | Instant -> "matchMedia(\"" + reducedQuery + "\").matches ? 0 : hover.duration"
            | _ -> "hover.duration"

        let guard =
            match policy with
            | Off -> "  if (matchMedia(\"" + reducedQuery + "\").matches) return;\n"
            | _ -> ""

        template
            .Replace("@HOVERS@", hovers |> List.map config |> String.concat "\n")
            .Replace("@DURATION@", duration)
            .Replace("@GUARD@", guard)

    let private indent (text: string) =
        text.TrimEnd('\n').Split '\n'
        |> Array.map (fun line -> if line = "" then line else "  " + line)
        |> String.concat "\n"

    let private resource (name: string) =
        use stream = Assembly.GetExecutingAssembly().GetManifestResourceStream name
        use reader = new StreamReader(stream)
        reader.ReadToEnd()

    // anime.js's MIT notice, for the copy a bundle carries. A /*! comment is a legal comment, which
    // esbuild keeps through bundling and minifying.
    let private notice =
        lazy
            (let copyright =
                (resource "LICENSE.anime.md").Split('\n')
                |> Array.map (fun line -> line.Trim())
                |> Array.find (fun line -> line.StartsWith "Copyright")

             "/*! anime.js v4.5.0 | MIT License | " + copyright + " */")

    /// <summary>The script that plays the hovers.</summary>
    /// <remarks>
    /// <para>A bundled source starts with anime.js's licence notice, as a <c>/*! ... */</c> comment, then a static import of <c>./anime.esm.js</c> that names only what the hovers use, for the site's bundler to resolve. A CDN source holds no static import: it loads the module with <c>import()</c> inside an async function, so it runs as a classic script.</para>
    /// <para>A token value is read with <c>getComputedStyle</c> each time a hover starts, never written as <c>var()</c>; where the site does not define the token, its fallback is used.</para>
    /// </remarks>
    /// <param name="source">Where anime.js comes from.</param>
    /// <param name="policy">What the script does for visitors who ask for reduced motion.</param>
    /// <param name="hovers">The hovers to play.</param>
    let entry (source: AnimeSource) (policy: ReducedMotion) (hovers: Hover list) : string =
        let names = names hovers |> String.concat ", "
        let body = body policy hovers

        match source with
        | Bundled -> notice.Value + "\nimport { " + names + " } from \"./anime.esm.js\";\n\n" + body
        | Cdn url ->
            "(async () => {\n  const url = "
            + literal url
            + ";\n  const anime = await import(url);\n  const { "
            + names
            + " } = anime;\n\n"
            + indent body
            + "\n})();\n"

    /// <summary>The anime.js 4.5.0 module embedded in the package.</summary>
    let anime () : string = resource "anime.esm.js"
